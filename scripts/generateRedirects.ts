/**
 * generateRedirects.ts - writes public/_redirects.
 *
 * The site used to have one page per drink, food and bar setup for every guest
 * count (/wine-for-wedding-100-guests/). Each now has a single page that holds
 * every guest count in a ledger (/wine-for-wedding/). This file sends every old
 * URL to its new page with a 301.
 *
 * Three splat rules per guest count N cover everything:
 *
 *   /*-N-guests/          the page, with a trailing slash
 *   /*-N-guests           the page, without one
 *   /og/*-N-guests.png    its share image
 *
 * The splat keeps any /food/ or /bar-setup/ prefix, so these rules cover drinks,
 * food and bar setup alike. That is 3 x 14 = 42 dynamic rules and no static
 * ones, well inside Cloudflare Pages' limits (2,000 static, 100 dynamic).
 *
 * Why not one rule per event: Cloudflare applies redirects before serving
 * files, so a prefix rule like /bar-setup/wedding-* would also catch the
 * current page /bar-setup/wedding-shower/ and redirect it, and rule order
 * cannot fix that. A rule anchored on "-N-guests" cannot match a current URL,
 * because no current URL ends that way. "-125-guests" does not trip the "-25"
 * rule either, since the hyphen before 25 is not there.
 *
 * Cloudflare's parser rejects domain-level rules, so the apex and pages.dev
 * redirects that used to live in this file are only kept as comments here;
 * they are not applied by this file.
 *
 * The output is derived data: it is gitignored and rewritten by every
 * `npm run generate`.
 */

import * as fs from 'fs';
import * as path from 'path';
import { fileURLToPath } from 'url';
import { redirectRules } from '../src/lib/redirects';

const __dirname = path.dirname(fileURLToPath(import.meta.url));

const header = [
  '# Generated by scripts/generateRedirects.ts. Do not edit.',
  '#',
  '# Old per-guest-count URLs (/wine-for-wedding-100-guests/) redirect to the',
  '# single page for that drink, food or event (/wine-for-wedding/).',
  '#',
  '# Domain-level redirects are not supported in _redirects. Configure them in',
  '# the Cloudflare dashboard instead:',
  '#   https://stocktheevent.pages.dev/* -> https://www.stocktheevent.com/:splat',
  '#   https://stocktheevent.com/*       -> https://www.stocktheevent.com/:splat',
  '',
];

const outputPath = path.join(__dirname, '../public/_redirects');
const rules = redirectRules();
fs.writeFileSync(outputPath, [...header, ...rules, ''].join('\n'));

console.log(`Wrote ${rules.length} redirect rules to public/_redirects`);
